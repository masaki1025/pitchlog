def test_game_state_constraints_and_migration_round_trip(
    disposable_postgres_cluster: Callable[
        [], AbstractContextManager[DisposablePostgres]
    ],
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """試合系4表の索引・必須列・不変性と migration 往復を検査する。"""
    with disposable_postgres_cluster() as cluster:
        monkeypatch.setenv(
            "PITCHLOG_MIGRATION_DATABASE_URL",
            _sqlalchemy_url(cluster.admin_dsn),
        )
        config = _alembic_config()
        command.upgrade(config, "head")

        with psycopg.connect(cluster.admin_dsn, autocommit=True) as connection:
            trigger, table, columns, enabled, function = (
                _game_lineup_trigger_catalog_contract(connection)
            )
            assert _normalize_sql(trigger) == _normalize_sql(
                _GAME_LINEUP_TRIGGER_DEFINITION
            )
            assert table == "game_lineups"
            assert columns == ["entries_with_uniform_number_snapshot"]
            assert enabled == "O"
            assert _normalize_sql(function) == _normalize_sql(
                _GAME_LINEUP_FUNCTION_DEFINITION
            )

            expected_indexes = {
                "uq_lineup_memories_active": (
                    "lineup_memories",
                    ["tenant_id", "team_record_id"],
                ),
                "uq_participation_intervals_active": (
                    "participation_intervals",
                    [
                        "tenant_id",
                        "game_id",
                        "slot_kind",
                        "slot",
                        "valid_from_d2",
                    ],
                ),
            }
            for index_name, (
                expected_table,
                expected_columns,
            ) in expected_indexes.items():
                definition, index_table, index_columns, predicate, unique = (
                    _index_catalog_contract(connection, index_name)
                )
                assert _normalize_sql(definition).startswith(
                    f"CREATE UNIQUE INDEX {index_name} "
                )
                assert index_table == expected_table
                assert index_columns == expected_columns
                assert predicate == "retired_at IS NULL"
                assert unique

            tenant_id = uuid4()
            self_team_id = uuid4()
            opponent_team_id = uuid4()
            game_id = uuid4()
            scheduled_at = datetime(2026, 9, 11, 10, 0, tzinfo=UTC)
            with connection.cursor() as cursor:
                cursor.execute(
                    "INSERT INTO tenants (id, name) VALUES (%s, %s)",
                    (tenant_id, "試合テストテナント"),
                )
                cursor.executemany(
                    """
                    INSERT INTO team_records (tenant_id, id, kind, name)
                    VALUES (%s, %s, %s, %s)
                    """,
                    [
                        (tenant_id, self_team_id, "self", "自チーム"),
                        (tenant_id, opponent_team_id, "opponent", "対戦相手"),
                    ],
                )

                game_values: dict[str, object] = {
                    "tenant_id": tenant_id,
                    "id": game_id,
                    "scheduled_at": scheduled_at,
                    "game_type_key": "official",
                    "tournament_key": "autumn",
                    "away_team_record_id": opponent_team_id,
                    "home_team_record_id": self_team_id,
                    "applied_rules": Jsonb({}),
                }
                insert_game = """
                    INSERT INTO games (
                        tenant_id,
                        id,
                        scheduled_at,
                        game_type_key,
                        tournament_key,
                        away_team_record_id,
                        home_team_record_id,
                        applied_rules
                    ) VALUES (
                        %(tenant_id)s,
                        %(id)s,
                        %(scheduled_at)s,
                        %(game_type_key)s,
                        %(tournament_key)s,
                        %(away_team_record_id)s,
                        %(home_team_record_id)s,
                        %(applied_rules)s
                    )
                """
                for required_column in (
                    "scheduled_at",
                    "game_type_key",
                    "tournament_key",
                ):
                    invalid_values = game_values | {
                        "id": uuid4(),
                        required_column: None,
                    }
                    with pytest.raises(
                        psycopg.errors.NotNullViolation,
                        match=required_column,
                    ):
                        cursor.execute(insert_game, invalid_values)

                cursor.execute(insert_game, game_values)
                lineup_id = uuid4()
                cursor.execute(
                    """
                    INSERT INTO game_lineups (
                        tenant_id,
                        id,
                        game_id,
                        team_record_id,
                        entries_with_uniform_number_snapshot
                    ) VALUES (%s, %s, %s, %s, %s)
                    """,
                    (
                        tenant_id,
                        lineup_id,
                        game_id,
                        self_team_id,
                        Jsonb([{"slot": "1", "uniform_number_snapshot": "10"}]),
                    ),
                )
                with pytest.raises(
                    psycopg.errors.CheckViolation,
                    match=(
                        "game_lineups.entries_with_uniform_number_snapshot is immutable"
                    ),
                ):
                    cursor.execute(
                        """
                        UPDATE game_lineups
                        SET entries_with_uniform_number_snapshot = %s
                        WHERE tenant_id = %s AND id = %s
                        """,
                        (
                            Jsonb(
                                [
                                    {
                                        "slot": "1",
                                        "uniform_number_snapshot": "11",
                                    }
                                ]
                            ),
                            tenant_id,
                            lineup_id,
                        ),
                    )

        command.downgrade(config, "0002_tenants_teams_players")
        with psycopg.connect(cluster.admin_dsn, autocommit=True) as connection:
            _assert_step_seven_objects_are_absent(connection)

        command.upgrade(config, "head")
        command.current(config, check_heads=True)
        command.check(config)
