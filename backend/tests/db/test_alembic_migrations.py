def _sqlalchemy_url(dsn: str) -> str:
    """使い捨てクラスタの conninfo から裸の PostgreSQL URL を作る。

    Args:
        dsn: 既存 factory が返す libpq conninfo。

    Returns:
        同じ接続先を指す裸の PostgreSQL URL。
    """
    parameters = conninfo_to_dict(dsn)
    required = {key: parameters.get(key) for key in ("host", "port", "dbname", "user")}
    if any(value is None for value in required.values()):
        raise AssertionError("使い捨てクラスタ DSN に接続先情報が不足している")

    password = parameters.get("password")
    return URL.create(
        "postgresql",
        username=str(required["user"]),
        password=None if password is None else str(password),
        host=str(required["host"]),
        port=int(str(required["port"])),
        database=str(required["dbname"]),
    ).render_as_string(hide_password=False)


