def _index_catalog_contract(
    connection: psycopg.Connection[Any], index_name: str
) -> tuple[str, str, list[str], str | None, bool]:
    """索引定義・対象表・列順・述語・一意性をカタログから取得する。"""
    with connection.cursor() as cursor:
        cursor.execute(
            """
            SELECT
                pg_get_indexdef(index_row.indexrelid, 0, true),
                table_relation.relname,
                ARRAY(
                    SELECT pg_get_indexdef(
                        index_row.indexrelid,
                        position,
                        true
                    )
                    FROM generate_series(
                        1,
                        index_row.indnkeyatts
                    ) AS position
                    ORDER BY position
                ),
                pg_get_expr(index_row.indpred, index_row.indrelid, true),
                index_row.indisunique
            FROM pg_index AS index_row
            JOIN pg_class AS index_relation
              ON index_relation.oid = index_row.indexrelid
            JOIN pg_class AS table_relation
              ON table_relation.oid = index_row.indrelid
            WHERE index_relation.relname = %s
            """,
            (index_name,),
        )
        row = cursor.fetchone()
    if row is None:
        raise AssertionError(f"索引が存在しない: {index_name}")
    predicate = None if row[3] is None else str(row[3])
    return str(row[0]), str(row[1]), list(row[2]), predicate, bool(row[4])


