def _assert_source_kind_rejections(
    cursor: psycopg.Cursor[Any],
    insert_statement: LiteralString,
    base_parameters: dict[str, object],
    kind_parameter: str,
    literal_kind: str,
    other_kind: str,
) -> None:
    """参照元 1 表について種別と台帳参照の負例 4 種を検査する。"""
