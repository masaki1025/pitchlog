def _alembic_config() -> Config:
    """Backend 配下の Alembic 設定を返す。

    Returns:
        migration コマンドに渡す設定。
    """
    return Config(str(_BACKEND_ROOT / "alembic.ini"))


def _sqlalchemy_url(dsn: str) -> str:
    """使い捨てクラスタの conninfo から裸の PostgreSQL URL を作る。

    Args:
        dsn: 既存 factory が返す libpq conninfo。

    Returns:
        同じ接続先を指す裸の PostgreSQL URL。
    """
    parameters = conninfo_to_dict(dsn)
    required = {key: parameters.get(key) for key in ("host", "port", "dbname", "user")}
    if any(value is None for value in required.values()):
        raise AssertionError("使い捨てクラスタ DSN に接続先情報が不足している")

    password = parameters.get("password")
    return URL.create(
        "postgresql",
        username=str(required["user"]),
        password=None if password is None else str(password),
        host=str(required["host"]),
        port=int(str(required["port"])),
        database=str(required["dbname"]),
    ).render_as_string(hide_password=False)


def test_schema_revision_and_application_engine_use_the_database(
    disposable_postgres_cluster: Callable[
        [], AbstractContextManager[DisposablePostgres]
    ],
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """空 DB で upgrade・head 検査・差分検査・実接続を完走する。"""
    with disposable_postgres_cluster() as cluster:
        database_url = _sqlalchemy_url(cluster.admin_dsn)
        monkeypatch.setenv("PITCHLOG_MIGRATION_DATABASE_URL", database_url)
        monkeypatch.setenv("PITCHLOG_DATABASE_URL", database_url)
        monkeypatch.setenv("PITCHLOG_DATABASE_POOLED", "false")
        config = _alembic_config()

        heads = ScriptDirectory.from_config(config).get_heads()
        assert heads == [_REVISION]

        command.upgrade(config, "head")
        command.current(config, check_heads=True)
        command.check(config)

        engine = create_database_engine()
        try:
            assert engine.dialect.driver == "psycopg"
            with engine.connect() as connection:
                assert connection.exec_driver_sql("SELECT 1").scalar_one() == 1
        finally:
            engine.dispose()


